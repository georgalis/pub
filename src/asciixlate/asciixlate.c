/*
 * returns 0 ok, -1 refused (message already printed). O_NONBLOCK keeps the
 * open of a fifo from waiting on a writer before the type can be refused.
 * The file is read to end of file, not to st_size: a /proc style file
 * reports size 0 and still has content.
 */
static int slurp(const char *path, const char *name, unsigned char **buf,
                 size_t *len, mode_t *mode)
{
    int fd = open(path, O_RDONLY | O_NONBLOCK);
    if (fd < 0) { warnx_("%s: cannot process (%s)", name, strerror(errno)); return -1; }

    struct stat sb;
    if (fstat(fd, &sb) != 0) {
        warnx_("%s: cannot process (%s)", name, strerror(errno));
        close(fd);
        return -1;
    }
    if (!S_ISREG(sb.st_mode)) {
        warnx_("%s: cannot process (not a regular file)", name);
        close(fd);
        return -1;
    }

    unsigned long long sz = sb.st_size > 0 ? (unsigned long long)sb.st_size : 0;
    size_t cap = sz < (unsigned long long)opt_max_size ? (size_t)sz + 1
                                                       : (size_t)opt_max_size + 1;
    if (cap < 4096) cap = 4096;
    unsigned char *b = xmalloc(cap);
    size_t got = 0;
    while (sz <= (unsigned long long)opt_max_size) {
        if (got == cap) {
            if (cap > (size_t)-1 / 2) fatal("input too large");
            cap *= 2;
            b = xrealloc(b, cap);
        }
        ssize_t r = read(fd, b + got, cap - got);
        if (r < 0) {
            if (errno == EINTR) continue;
            warnx_("%s: cannot process (%s)", name, strerror(errno));
            free(b);
            close(fd);
            return -1;
        }
        if (r == 0) break;
        got += (size_t)r;
        if (got > sz) sz = got;
    }
    close(fd);
    if (sz > (unsigned long long)opt_max_size) {
        warnx_("%s: cannot process (%llu bytes exceeds limit %lu; raise with "
               "--max-size)", name, sz, opt_max_size);
        free(b);
        return -1;
    }

    if (!opt_allow_binary) {
        size_t sniff = got < BINARY_SNIFF ? got : BINARY_SNIFF;
        if (memchr(b, '\0', sniff)) {
            warnx_("%s: cannot process (binary: NUL byte in first %zu bytes; "
                   "override with --allow-binary)", name, sniff);
            free(b);
            return -1;
        }
    }

    *buf = b;
    *len = got;
    *mode = sb.st_mode & 07777;
    return 0;
}

static void on_signal(int sig)
{
    char *t = tmp_live;
    if (t) unlink(t);
    _exit(128 + sig);
}

/* atomic replace: write a sibling temp file, fsync, rename */
static int write_atomic(const char *path, const char *data, size_t len,
                        mode_t mode)
{
    size_t dlen = strlen(path);
    char *tmp = xmalloc(dlen + sizeof ".asciixlate.XXXXXX");
    const char *slash = strrchr(path, '/');
    if (slash) {
        size_t dir = (size_t)(slash - path) + 1;
        memcpy(tmp, path, dir);
        snprintf(tmp + dir, dlen + sizeof ".asciixlate.XXXXXX" - dir,
                 ".asciixlate.XXXXXX");
    } else {
        snprintf(tmp, dlen + sizeof ".asciixlate.XXXXXX",
                 ".asciixlate.XXXXXX");
    }

    int fd = mkstemp(tmp);
    if (fd < 0) { warnx_("%s: %s", tmp, strerror(errno)); free(tmp); return -1; }
    tmp_live = tmp;

    size_t off = 0;
    while (off < len) {
        ssize_t w = write(fd, data + off, len - off);
        if (w < 0) {
            if (errno == EINTR) continue;
            warnx_("%s: write failed (%s)", tmp, strerror(errno));
            close(fd); unlink(tmp); tmp_live = NULL; free(tmp);
            return -1;
        }
        off += (size_t)w;
    }
    if (fchmod(fd, mode) != 0)                  /* result stays mode 0600 */
        warnx_("%s: mode not carried over (%s)", path, strerror(errno));
    if (fsync(fd) != 0) {
        warnx_("%s: fsync failed (%s)", tmp, strerror(errno));
        close(fd); unlink(tmp); tmp_live = NULL; free(tmp);
        return -1;
    }
    if (close(fd) != 0) {
        warnx_("%s: close failed (%s)", tmp, strerror(errno));
        unlink(tmp); tmp_live = NULL; free(tmp);
        return -1;
    }
    if (rename(tmp, path) != 0) {
        warnx_("%s: rename failed (%s)", path, strerror(errno));
        unlink(tmp); tmp_live = NULL; free(tmp);
        return -1;
    }
    tmp_live = NULL;
    free(tmp);
    return 0;
}

/*
 * Write to a named output. A path that already exists and is not a regular
 * file (a device, a fifo) is written through directly --- replacing such a
 * target by rename would destroy the node. Everything else is replaced
 * atomically: an existing regular file keeps its mode, a new one takes
 * 0666 less the umask, and a symlink is followed so the link survives.
 */
static int write_out(const char *arg, const char *data, size_t len)
{
    struct stat sb;
    char *rp = realpath(arg, NULL);             /* NULL when not yet there */
    const char *path = rp ? rp : arg;
    mode_t um = umask(0), mode;
    int rc;

    umask(um);
    mode = 0666 & ~um;
    if (stat(path, &sb) == 0 && S_ISREG(sb.st_mode)) mode = sb.st_mode & 07777;
    else if (stat(path, &sb) == 0) {
        int fd = open(path, O_WRONLY);
        if (fd < 0) { warnx_("%s: %s", path, strerror(errno)); free(rp); return -1; }
        size_t off = 0;
        while (off < len) {
            ssize_t w = write(fd, data + off, len - off);
            if (w < 0) {
                if (errno == EINTR) continue;
                warnx_("%s: write failed (%s)", path, strerror(errno));
                close(fd);
                free(rp);
                return -1;
            }
            off += (size_t)w;
        }
        if (close(fd) != 0) {
            warnx_("%s: close failed (%s)", path, strerror(errno));
            free(rp);
            return -1;
        }
        free(rp);
        return 0;
    }
    rc = write_atomic(path, data, len, mode);
    free(rp);
    return rc;
}

static int write_stdout(const char *data, size_t len)
{
    if (len && fwrite(data, 1, len, stdout) != len) {
        warnx_("stdout: write failed (%s)", strerror(errno));
        return -1;
    }
    if (fflush(stdout) != 0) {
        warnx_("stdout: write failed (%s)", strerror(errno));
        return -1;
    }
    return 0;
}

/*
 * Standard input as a stream: read a block, convert what is complete, write,
 * carry the tail. Memory is bounded by the block, whatever the input size.
 * Each read is converted as it arrives, so a slow writer is not held for a
 * full block. One trailing space is held back from each write, because the
 * pictograph rule may still retract it. returns 0 ok, -1 failed (reported).
 */
static int filter_stdin(const Table *t, Stats *st)
{
    size_t cap = (size_t)opt_block, have = 0;
    unsigned char *b = xmalloc(cap);
    Conv cs = {0, 0, '\n'};
    Buf out;
    int eof = 0, first = 1, rc = 0;

    buf_init(&out, cap + cap / 8 + 64);
    while (!eof) {
        ssize_t r = read(STDIN_FILENO, b + have, cap - have);
        if (r < 0) {
            if (errno == EINTR) continue;
            warnx_("stdin: read failed (%s)", strerror(errno));
            rc = -1;
            break;
        }
        if (r == 0) eof = 1;
        have += (size_t)r;

        if (first && have) {                    /* sniff before any output */
            size_t sniff = have < BINARY_SNIFF ? have : BINARY_SNIFF;
            first = 0;
            if (!opt_allow_binary && memchr(b, '\0', sniff)) {
                warnx_("stdin: cannot process (binary: NUL byte in the first "
                       "%zu bytes; override with --allow-binary)", sniff);
                rc = -1;
                break;
            }
        }

        size_t used = convert(t, b, have, eof, &out, st, &cs);
        st->bytes_in += used;
        memmove(b, b + used, have - used);
        have -= used;

        size_t n = out.n;
        if (!eof && n && out.p[n - 1] == ' ') n--;
        if (n && !opt_dryrun && !opt_report && write_stdout(out.p, n) != 0) {
            rc = -1;
            break;
        }
        st->bytes_out += n;
        if (n) cs.last = out.p[n - 1];
        memmove(out.p, out.p + n, out.n - n);
        out.n -= n;
    }
    free(out.p);
    free(b);
    return rc;
}

/* --------------------------------------------------------------- listing -- */

static void print_escaped(const char *s, size_t n)
{
    for (size_t i = 0; i < n; i++) {
        unsigned char c = (unsigned char)s[i];
        if (c == '\\') fputs("\\\\", stdout);
        else if (c == '"') fputs("\\\"", stdout);
        else if (c == '\n') fputs("\\n", stdout);
        else if (c == '\t') fputs("\\t", stdout);
        else if (c >= 0x20 && c < 0x7F) putchar((int)c);
        else printf("\\x%02X", c);
    }
}

static int list_cmp(const void *a, const void *b)
{
    const Slot *x = a, *y = b;
    return x->cp < y->cp ? -1 : x->cp > y->cp;
}

static void table_list(const Table *t)
{
    Slot *v = xmalloc((t->mask + 1) * sizeof *v);
    size_t n = 0;
    for (size_t i = 0; i <= t->mask; i++)
        if (t->slot[i].used) v[n++] = t->slot[i];
    qsort(v, n, sizeof *v, list_cmp);

    printf("# %zu single-code-point rules, %zu multi-code-point rules\n",
           n, t->multi_n);
    for (size_t i = 0; i < n; i++) {
        printf("U+%04X\t\"", v[i].cp);
        print_escaped(v[i].repl, v[i].len);
        printf("\"\n");
    }
    for (size_t i = 0; i < t->multi_n; i++) {
        const MultiRule *m = &t->multi[i];
        fputs("\\x", stdout);
        for (size_t j = 0; j < m->key_len; j++)
            printf("%s%02X", j ? "\\x" : "", (unsigned char)m->key[j]);
        printf("\t\"");
        print_escaped(m->repl, m->repl_len);
        printf("\"\n");
    }
    free(v);
}

