static void warnx_(const char *fmt, ...)
{
    va_list ap;
    fprintf(stderr, "%s: ", PROG);
    va_start(ap, fmt);
    vfprintf(stderr, fmt, ap);
    va_end(ap);
    fputc('\n', stderr);
}

static void fatal(const char *fmt, ...)
{
    va_list ap;
    fprintf(stderr, "%s: ", PROG);
    va_start(ap, fmt);
    vfprintf(stderr, fmt, ap);
    va_end(ap);
    fputc('\n', stderr);
    exit(EX_USAGE);
}

static void *xmalloc(size_t n)
{
    void *p = malloc(n ? n : 1);
    if (!p) fatal("out of memory");
    return p;
}

static void *xrealloc(void *p, size_t n)
{
    void *q = realloc(p, n ? n : 1);
    if (!q) fatal("out of memory");    /* p is leaked, but we exit */
    return q;
}

static char *xstrndup(const char *s, size_t n)
{
    char *p = xmalloc(n + 1);
    memcpy(p, s, n);
    p[n] = '\0';
    return p;
}

/* ------------------------------------------------------------------ utf8 -- */

/*
 * Decode one code point at p (p < end). On success returns bytes consumed
 * (1..4) and sets *cp. On a malformed sequence returns 0 and leaves *cp
 * undefined; the caller advances by one byte and emits the marker.
 */
static size_t utf8_decode(const unsigned char *p, const unsigned char *end,
                          uint32_t *cp)
{
    unsigned c = *p, need;
    uint32_t v;

    if (c < 0x80) { *cp = c; return 1; }
    if ((c & 0xE0) == 0xC0) { need = 2; v = c & 0x1Fu; }
    else if ((c & 0xF0) == 0xE0) { need = 3; v = c & 0x0Fu; }
    else if ((c & 0xF8) == 0xF0) { need = 4; v = c & 0x07u; }
    else return 0;

    if ((size_t)(end - p) < need) return 0;
    for (unsigned i = 1; i < need; i++) {
        if ((p[i] & 0xC0) != 0x80) return 0;
        v = (v << 6) | (p[i] & 0x3Fu);
    }
    if (need == 2 && v < 0x80) return 0;
    if (need == 3 && (v < 0x800 || (v >= 0xD800 && v <= 0xDFFF))) return 0;
    if (need == 4 && (v < 0x10000 || v > 0x10FFFF)) return 0;
    *cp = v;
    return need;
}

static size_t utf8_encode(uint32_t cp, unsigned char *out)
{
    if (cp < 0x80) { out[0] = (unsigned char)cp; return 1; }
    if (cp < 0x800) {
        out[0] = (unsigned char)(0xC0 | (cp >> 6));
        out[1] = (unsigned char)(0x80 | (cp & 0x3F));
        return 2;
    }
    if (cp < 0x10000) {
        out[0] = (unsigned char)(0xE0 | (cp >> 12));
        out[1] = (unsigned char)(0x80 | ((cp >> 6) & 0x3F));
        out[2] = (unsigned char)(0x80 | (cp & 0x3F));
        return 3;
    }
    out[0] = (unsigned char)(0xF0 | (cp >> 18));
    out[1] = (unsigned char)(0x80 | ((cp >> 12) & 0x3F));
    out[2] = (unsigned char)(0x80 | ((cp >> 6) & 0x3F));
    out[3] = (unsigned char)(0x80 | (cp & 0x3F));
    return 4;
}

/* ------------------------------------------------------------ pictograph -- */

/*
 * A pictograph is a glyph that stands as a word of its own: emoji and the
 * symbol blocks emoji are drawn from. When a rule deletes one, the space
 * that set it apart is deleted with it (convert). Deliberately excluded:
 * letters, punctuation, and the invisibles (soft hyphen, zero-width and
 * bidi marks), whose deletion must not join or split words.
 */
static int is_pict(uint32_t cp)
{
    return (cp >= 0x1F000 && cp <= 0x1FAFF) ||   /* emoji planes, flags */
           (cp >= 0x2190 && cp <= 0x21FF) ||     /* arrows */
           (cp >= 0x2300 && cp <= 0x23FF) ||     /* miscellaneous technical */
           (cp >= 0x25A0 && cp <= 0x27BF) ||     /* geometric, symbols, dingbats */
           (cp >= 0x2900 && cp <= 0x297F) ||     /* supplemental arrows B */
           (cp >= 0x2B00 && cp <= 0x2BFF) ||     /* stars, heavy arrows */
           cp == 0x3030 || cp == 0x303D || cp == 0x3297 || cp == 0x3299;
}

/* ----------------------------------------------------------------- table -- */

static size_t hash_cp(uint32_t cp, size_t mask)
{
    cp *= 2654435761u;             /* Knuth multiplicative */
    return (cp >> 11) & mask;
}

static void table_init(Table *t, size_t hint)
{
    size_t n = 64;
    while (n < hint * 2) n <<= 1;
    t->slot = xmalloc(n * sizeof *t->slot);
    memset(t->slot, 0, n * sizeof *t->slot);
    t->mask = n - 1;
    t->count = 0;
    t->multi = NULL;
    t->multi_n = t->multi_cap = 0;
    t->multi_max = 0;
    memset(t->multi_first, 0, sizeof t->multi_first);
    memset(t->ascii_mapped, 0, sizeof t->ascii_mapped);
    memset(t->ascii_stop, 0, sizeof t->ascii_stop);
}

/* double the slot array; open addressing needs free slots to terminate */
static void table_grow(Table *t)
{
    Slot *old = t->slot;
    size_t n = t->mask + 1;
    if (n > (size_t)-1 / 2 / sizeof *old) fatal("rule table too large");
    t->slot = xmalloc(2 * n * sizeof *old);
    memset(t->slot, 0, 2 * n * sizeof *old);
    t->mask = 2 * n - 1;
    for (size_t k = 0; k < n; k++) {
        if (!old[k].used) continue;
        size_t i = hash_cp(old[k].cp, t->mask);
        while (t->slot[i].used) i = (i + 1) & t->mask;
        t->slot[i] = old[k];
    }
    free(old);
}

/* repl must outlive the table (rodata or heap owned elsewhere) */
static void table_set(Table *t, uint32_t cp, const char *repl, size_t len,
                      int owned)
{
    if ((t->count + 1) * 2 > t->mask + 1) table_grow(t);
    size_t i = hash_cp(cp, t->mask);
    while (t->slot[i].used) {
        if (t->slot[i].cp == cp) break;
        i = (i + 1) & t->mask;
    }
    if (!t->slot[i].used) { t->slot[i].used = 1; t->count++; }
    else if (t->slot[i].owned) free((char *)(uintptr_t)t->slot[i].repl);
    t->slot[i].owned = (uint8_t)owned;
    t->slot[i].cp = cp;
    t->slot[i].repl = repl;
    t->slot[i].len = (uint16_t)len;
    if (cp < 128) t->ascii_mapped[cp] = t->ascii_stop[cp] = 1;
}

static const Slot *table_get(const Table *t, uint32_t cp)
{
    size_t i = hash_cp(cp, t->mask);
    while (t->slot[i].used) {
        if (t->slot[i].cp == cp) return &t->slot[i];
        i = (i + 1) & t->mask;
    }
    return NULL;
}

static void table_load_defaults(Table *t)
{
    for (size_t i = 0; i < TRANSLIT_TABLE_N; i++)
        table_set(t, translit_table[i].cp, translit_table[i].repl,
                  strlen(translit_table[i].repl), 0);
}

static void table_free(Table *t)
{
    for (size_t i = 0; i <= t->mask; i++)
        if (t->slot[i].used && t->slot[i].owned)
            free((char *)(uintptr_t)t->slot[i].repl);
    for (size_t i = 0; i < t->multi_n; i++) free(t->multi[i].repl);
    free(t->slot);
    free(t->multi);
    free(census);
}

static int multi_cmp(const void *a, const void *b)
{
    const MultiRule *x = a, *y = b;
    if (x->key_len != y->key_len) return x->key_len < y->key_len ? 1 : -1;
    return memcmp(x->key, y->key, x->key_len);
}

static void table_add_multi(Table *t, const unsigned char *key, size_t klen,
                            char *repl, size_t rlen)
{
    uint8_t pict = 0;
    for (const unsigned char *q = key, *e = key + klen; q < e; ) {
        uint32_t cp;
        size_t u = utf8_decode(q, e, &cp);
        if (u && is_pict(cp)) pict = 1;
        q += u ? u : 1;
    }
    for (size_t i = 0; i < t->multi_n; i++) {       /* a later rule wins */
        MultiRule *m = &t->multi[i];
        if (m->key_len == klen && memcmp(m->key, key, klen) == 0) {
            free(m->repl);
            m->repl = repl;
            m->repl_len = rlen;
            return;
        }
    }
    if (t->multi_n == t->multi_cap) {
        t->multi_cap = t->multi_cap ? t->multi_cap * 2 : 16;
        t->multi = xrealloc(t->multi, t->multi_cap * sizeof *t->multi);
    }
    MultiRule *m = &t->multi[t->multi_n++];
    memcpy(m->key, key, klen);
    m->key_len = klen;
    m->repl = repl;
    m->repl_len = rlen;
    m->pict = pict;
    t->multi_first[key[0]] = 1;
    if (klen > t->multi_max) t->multi_max = klen;
    if (key[0] < 128) t->ascii_stop[key[0]] = 1;
}

/* ------------------------------------------------------------ config file -- */

/*
 * Grammar (one rule per line):
 *
 *     KEY <whitespace> VALUE
 *
 * KEY is a run of non-whitespace bytes, interpreted as:
 *     U+2014 | u+2014 | 0x2014     a code point
 *     \xE2\x80\x94                 an explicit byte sequence
 *     =anything                    forced literal (drops the '=')
 *     anything else                literal UTF-8, exactly as pasted
 *
 * VALUE is the rest of the line. A VALUE that opens with a double quote
 * runs to its closing quote and is taken exactly, with \\ \" \n \t \r \xHH
 * recognised; only a comment may follow it. Otherwise a '#' preceded by
 * whitespace begins a trailing comment and the remainder is trimmed. An
 * empty VALUE is an error; write "" to delete a character.
 * A '#' as the first non-blank character makes the whole line a comment.
 */

static int parse_hex(const char *s, const char *e, uint32_t *out)
{
    uint32_t v = 0;
    if (s == e || (size_t)(e - s) > 6) return -1;
    for (; s < e; s++) {
        int d;
        if (*s >= '0' && *s <= '9') d = *s - '0';
        else if (*s >= 'a' && *s <= 'f') d = *s - 'a' + 10;
        else if (*s >= 'A' && *s <= 'F') d = *s - 'A' + 10;
        else return -1;
        v = v * 16 + (uint32_t)d;
    }
    if (v > 0x10FFFF) return -1;
    *out = v;
    return 0;
}

/* returns bytes written to out, or -1 */
static long key_to_bytes(const char *tok, size_t len, unsigned char *out,
                         size_t outcap, const char **why)
{
    uint32_t cp;

    if (len == 0) { *why = "empty key"; return -1; }

    if (tok[0] == '=') {                                 /* forced literal */
        tok++; len--;
        if (len == 0) { *why = "empty key"; return -1; }
    }
    else if (len >= 3 && (tok[0] == 'U' || tok[0] == 'u') && tok[1] == '+') {
        if (parse_hex(tok + 2, tok + len, &cp) != 0 ||
            (cp >= 0xD800 && cp <= 0xDFFF)) {
            *why = "bad U+ code point"; return -1;
        }
        return (long)utf8_encode(cp, out);
    }
    else if (len >= 3 && tok[0] == '0' && (tok[1] == 'x' || tok[1] == 'X')) {
        if (parse_hex(tok + 2, tok + len, &cp) != 0 ||
            (cp >= 0xD800 && cp <= 0xDFFF)) {
            *why = "bad 0x code point"; return -1;
        }
        return (long)utf8_encode(cp, out);
    }
    else if (len >= 4 && tok[0] == '\\' && (tok[1] == 'x' || tok[1] == 'X')) {
        size_t n = 0, i = 0;
        while (i < len) {
            if (i + 4 > len || tok[i] != '\\' ||
                (tok[i + 1] != 'x' && tok[i + 1] != 'X')) {
                *why = "bad \\xHH byte sequence"; return -1;
            }
            if (parse_hex(tok + i + 2, tok + i + 4, &cp) != 0 || cp > 0xFF) {
                *why = "bad \\xHH byte sequence"; return -1;
            }
            if (n >= outcap) { *why = "key too long"; return -1; }
            out[n++] = (unsigned char)cp;
            i += 4;
        }
        return (long)n;
    }

    if (len > outcap) { *why = "key too long"; return -1; }
    memcpy(out, tok, len);
    return (long)len;
}

/* unescape a quoted VALUE in place; returns length or -1 */
static long unquote(const char *s, size_t len, char *out, size_t outcap,
                    const char **why)
{
    size_t n = 0, i = 0;
    while (i < len) {
        if (n >= outcap) { *why = "replacement too long"; return -1; }
        if (s[i] != '\\') { out[n++] = s[i++]; continue; }
        if (i + 1 >= len) { *why = "trailing backslash"; return -1; }
        switch (s[i + 1]) {
        case '\\': out[n++] = '\\'; i += 2; break;
        case '"':  out[n++] = '"';  i += 2; break;
        case 'n':  out[n++] = '\n'; i += 2; break;
        case 't':  out[n++] = '\t'; i += 2; break;
        case 'r':  out[n++] = '\r'; i += 2; break;
        case 'x': case 'X': {
            uint32_t v;
            if (i + 4 > len || parse_hex(s + i + 2, s + i + 4, &v) != 0) {
                *why = "bad \\xHH escape"; return -1;
            }
            out[n++] = (char)v;
            i += 4;
            break;
        }
        default: *why = "unknown escape"; return -1;
        }
    }
    return (long)n;
}

static void config_line(Table *t, char *line, const char *path, int lineno)
{
    char *p = line;
    const char *why = "";

    while (*p == ' ' || *p == '\t') p++;
    if (*p == '\0' || *p == '\n' || *p == '#') return;

    /* KEY */
    char *ks = p;
    while (*p && *p != ' ' && *p != '\t' && *p != '\n') p++;
    size_t klen = (size_t)(p - ks);

    /* separator */
    if (*p != ' ' && *p != '\t')
        fatal("%s:%d: no replacement (key and value are separated by "
              "whitespace)", path, lineno);
    while (*p == ' ' || *p == '\t') p++;

    /*
     * VALUE: to end of line. A quoted value is scanned to its closing quote
     * first, so a '#' inside the quotes is data; what follows the quote may
     * only be a comment. An unquoted value loses a whitespace-preceded
     * trailing comment.
     */
    char *vs = p;
    char *ve = vs + strlen(vs);
    while (ve > vs && (ve[-1] == '\n' || ve[-1] == '\r')) ve--;
    char *cq = NULL;                            /* closing quote, if quoted */
    if (*vs == '"') {
        for (char *q = vs + 1; q < ve; q++) {
            if (*q == '\\' && q + 1 < ve) { q++; continue; }
            if (*q == '"') { cq = q; break; }
        }
    }
    if (cq) {
        char *q = cq + 1;
        while (q < ve && (*q == ' ' || *q == '\t')) q++;
        if (q < ve && (*q != '#' || q == cq + 1))
            fatal("%s:%d: text after the closing quote", path, lineno);
        ve = cq + 1;
    } else {
        for (char *q = vs; q < ve; q++) {
            if (*q == '#' && q > vs && (q[-1] == ' ' || q[-1] == '\t')) {
                ve = q;
                break;
            }
        }
        while (ve > vs && (ve[-1] == ' ' || ve[-1] == '\t')) ve--;
    }
    size_t vlen = (size_t)(ve - vs);

    if (vlen == 0)
        fatal("%s:%d: empty replacement; write \"\" to delete the character",
              path, lineno);

    char rbuf[CFG_MAX_REPL];
    long rlen;
    if (cq) {
        rlen = unquote(vs + 1, vlen - 2, rbuf, sizeof rbuf, &why);
        if (rlen < 0) fatal("%s:%d: %s", path, lineno, why);
    } else {
        if (vlen >= sizeof rbuf)
            fatal("%s:%d: replacement too long", path, lineno);
        memcpy(rbuf, vs, vlen);
        rlen = (long)vlen;
    }

    unsigned char kbuf[CFG_MAX_KEY];
    long kb = key_to_bytes(ks, klen, kbuf, sizeof kbuf, &why);
    if (kb < 0) fatal("%s:%d: %s", path, lineno, why);

    char *repl = xstrndup(rbuf, (size_t)rlen);

    /* one code point -> hash; more than one -> longest-match list */
    uint32_t cp;
    size_t used = utf8_decode(kbuf, kbuf + kb, &cp);
    if (used == (size_t)kb && used > 0)
        table_set(t, cp, repl, (size_t)rlen, 1);
    else
        table_add_multi(t, kbuf, (size_t)kb, repl, (size_t)rlen);
}

static int config_load(Table *t, const char *path, int required)
{
    FILE *f = fopen(path, "r");
    if (!f) {
        if (required) fatal("%s: %s", path, strerror(errno));
        return 0;
    }
    char line[4096];
    int lineno = 0;
    while (fgets(line, sizeof line, f)) {
        lineno++;
        if (!strchr(line, '\n') && !feof(f)) {
            fclose(f);
            fatal("%s:%d: line exceeds %zu bytes", path, lineno,
                  sizeof line - 1);
        }
        config_line(t, line, path, lineno);
    }
    if (ferror(f)) { fclose(f); fatal("%s: read error", path); }
    fclose(f);
    if (opt_verbose) warnx_("config: %s", path);
    return 1;
}

static void config_discover(Table *t, const char *explicit_path)
{
    if (explicit_path) { config_load(t, explicit_path, 1); return; }

    const char *env = getenv("ASCIIXLATE_CONFIG");
    if (env && *env) { config_load(t, env, 1); return; }

    const char *home = getenv("HOME");
    if (home && *home) {
        size_t n = strlen(home) + sizeof "/.asciixlate";
        char *p = xmalloc(n);
        snprintf(p, n, "%s/.asciixlate", home);
        config_load(t, p, 0);
        free(p);
    }
}

