/* open-addressing set keyed by code point; n == 0 marks a free slot */
static void census_note(uint32_t cp)
{
    if ((census_n + 1) * 2 > census_cap) {
        size_t ncap = census_cap ? census_cap * 2 : 256;
        Census *nc = xmalloc(ncap * sizeof *nc);
        memset(nc, 0, ncap * sizeof *nc);
        for (size_t k = 0; k < census_cap; k++) {
            if (!census[k].n) continue;
            size_t h = hash_cp(census[k].cp, ncap - 1);
            while (nc[h].n) h = (h + 1) & (ncap - 1);
            nc[h] = census[k];
        }
        free(census);
        census = nc;
        census_cap = ncap;
    }
    size_t h = hash_cp(cp, census_cap - 1);
    while (census[h].n) {
        if (census[h].cp == cp) { census[h].n++; return; }
        h = (h + 1) & (census_cap - 1);
    }
    census[h].cp = cp;
    census[h].n = 1;
    census_n++;
}

static int census_cmp(const void *a, const void *b)
{
    const Census *x = a, *y = b;
    if (x->n != y->n) return x->n < y->n ? 1 : -1;
    return x->cp < y->cp ? -1 : x->cp > y->cp;
}

static void census_print(void)
{
    if (census_n == 0) {
        printf("# every character had a mapping; nothing to report\n");
        return;
    }
    size_t w = 0;                               /* compact, then sort */
    for (size_t k = 0; k < census_cap; k++)
        if (census[k].n) census[w++] = census[k];
    qsort(census, census_n, sizeof *census, census_cmp);
    printf("# asciixlate --report: unmapped code points, most frequent first.\n"
           "# Edit the replacements and append to ~/.asciixlate\n");
    for (size_t i = 0; i < census_n; i++) {
        unsigned char u[4];
        size_t n = utf8_encode(census[i].cp, u);
        printf("U+%04X\t%s\t# %zu occurrence%s, bytes",
               census[i].cp, DEFAULT_MARKER, census[i].n,
               census[i].n == 1 ? "" : "s");
        for (size_t j = 0; j < n; j++) printf(" %02X", u[j]);
        putchar('\n');
    }
}

/* ------------------------------------------------------------- conversion -- */

typedef struct { char *p; size_t n, cap; } Buf;

static void buf_init(Buf *b, size_t cap)
{
    b->p = xmalloc(cap);
    b->n = 0;
    b->cap = cap;
}

static void buf_put(Buf *b, const void *src, size_t n)
{
    if (b->n + n > b->cap) {
        while (b->n + n > b->cap) {
            if (b->cap > (size_t)-1 / 2) fatal("output too large");
            b->cap *= 2;
        }
        b->p = xrealloc(b->p, b->cap);
    }
    memcpy(b->p + b->n, src, n);
    b->n += n;
}

typedef struct {                   /* conversion state carried between blocks */
    int del;                       /* inside a run of deleted pictographs */
    int lead;                      /* that run began after a blank */
    char last;                     /* last byte already flushed; '\n' at start */
} Conv;

static int at_blank(const Buf *b, const Conv *cs)
{
    char c = b->n ? b->p[b->n - 1] : cs->last;
    return c == ' ' || c == '\t' || c == '\n';
}

/*
 * Convert in[0..len) into out and return the bytes consumed. With eof set
 * everything is consumed. Without it (a block of a stream) conversion stops
 * short of a tail that the next block could complete: an unfinished UTF-8
 * sequence, or a byte that can begin a multi-code-point rule with less
 * than the longest key after it. The caller moves that tail to the front
 * of its buffer and reads on, so a block edge never changes the result.
 *
 * Deleted pictographs. A rule that maps a pictograph to the empty string
 * removes a word-like glyph, and the blank that set it apart would be left
 * doubled, leading, or trailing. So when the deleted run began after a
 * blank (or at the start of a line) one adjacent space goes with it: the
 * space that follows, or at end of line the space already written before
 * it. A pictograph abutting a word on its left keeps the following space,
 * the only separator there is. del holds across further deletions (joiners,
 * variation selectors, more pictographs) and ends at anything emitted. The
 * retracted space is always still in out: a stream never flushes a
 * trailing space until something follows it.
 */
static size_t convert(const Table *t, const unsigned char *in, size_t len,
                      int eof, Buf *out, Stats *st, Conv *cs)
{
    const unsigned char *p = in, *end = in + len;

    while (p < end) {
        if (cs->del && *p < 0x80) {
            if (cs->lead && *p == ' ' && !t->ascii_stop[' ']) {
                p++; cs->del = 0;
                continue;
            }
            if (cs->lead && (*p == '\n' || *p == '\r') &&
                out->n && out->p[out->n - 1] == ' ') out->n--;
            cs->del = 0;
        }

        if (!eof) {                             /* leave a completable tail */
            size_t left = (size_t)(end - p);
            if (t->multi_first[*p] && left < t->multi_max) break;
            if (*p >= 0xC2 && *p <= 0xF4 &&
                left < (size_t)(*p < 0xE0 ? 2 : *p < 0xF0 ? 3 : 4)) break;
        }

        /* multi-code-point rules, longest first */
        if (t->multi_n && t->multi_first[*p]) {
            size_t i;
            for (i = 0; i < t->multi_n; i++) {
                const MultiRule *m = &t->multi[i];
                if ((size_t)(end - p) >= m->key_len &&
                    memcmp(p, m->key, m->key_len) == 0) {
                    if (m->repl_len) cs->del = 0;
                    else if (m->pict && !cs->del) {
                        cs->del = 1; cs->lead = at_blank(out, cs);
                    }
                    buf_put(out, m->repl, m->repl_len);
                    p += m->key_len;
                    st->replaced++;
                    break;
                }
            }
            if (i < t->multi_n) continue;
        }

        /* plain ASCII with no rule and no multi-rule start: the common case */
        if (*p < 0x80 && !t->ascii_stop[*p]) {
            const unsigned char *run = p;
            while (p < end && *p < 0x80 && !t->ascii_stop[*p]) p++;
            buf_put(out, run, (size_t)(p - run));
            continue;
        }

        uint32_t cp;
        size_t used = utf8_decode(p, end, &cp);
        if (used == 0) {                        /* malformed byte */
            st->invalid++;
            cs->del = 0;
            if (opt_keep) buf_put(out, p, 1);
            else buf_put(out, marker, marker_len);
            p++;
            continue;
        }

        const Slot *s = table_get(t, cp);
        if (s) {
            if (s->len) cs->del = 0;
            else if (is_pict(cp) && !cs->del) {
                cs->del = 1; cs->lead = at_blank(out, cs);
            }
            buf_put(out, s->repl, s->len);
            st->replaced++;
            p += used;
            continue;
        }

        if (cp < 0x80) {                        /* ASCII without a rule */
            buf_put(out, p, 1);
            p += used;
            continue;
        }

        st->unmapped++;
        cs->del = 0;
        if (opt_report) census_note(cp);
        if (opt_keep) buf_put(out, p, used);
        else buf_put(out, marker, marker_len);
        p += used;
    }
    if (eof && cs->del && cs->lead && out->n && out->p[out->n - 1] == ' ')
        out->n--;
    return (size_t)(p - in);
}

