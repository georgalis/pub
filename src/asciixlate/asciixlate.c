typedef struct {                   /* single-code-point rule */
    uint32_t cp;
    const char *repl;              /* NUL-terminated; may point into rodata */
    uint16_t len;
    uint8_t used;
    uint8_t owned;                 /* repl is heap, freed with the table */
} Slot;

typedef struct {                   /* multi-code-point (byte string) rule */
    unsigned char key[CFG_MAX_KEY];
    size_t key_len;
    char *repl;
    size_t repl_len;
    uint8_t pict;                  /* key holds a pictograph (see is_pict) */
} MultiRule;

typedef struct {
    Slot *slot;
    size_t mask;                   /* table size - 1, power of two */
    size_t count;                  /* grows at half load: see table_set */

    MultiRule *multi;              /* sorted by descending key_len */
    size_t multi_n, multi_cap;
    uint8_t multi_first[256];      /* first-byte bitmap for the fast path */
    size_t multi_max;              /* longest key: the stream carry bound */

    uint8_t ascii_mapped[128];     /* an ASCII code point carries a rule */
    uint8_t ascii_stop[128];       /* ascii_mapped, or first byte of a multi
                                      rule: ends the verbatim ASCII run */
} Table;

typedef struct {                   /* counters for one file */
    size_t bytes_in, bytes_out;
    size_t replaced;               /* rule or table hits */
    size_t unmapped;               /* no mapping; marker emitted */
    size_t invalid;                /* malformed UTF-8 bytes */
} Stats;

typedef struct {                   /* unmapped code point census for --report */
    uint32_t cp;
    size_t n;
} Census;

