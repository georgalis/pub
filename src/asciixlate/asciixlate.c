static unsigned long parse_size(const char *s)
{
    char *e;
    unsigned long v, mul = 1;
    errno = 0;
    if (*s < '0' || *s > '9') fatal("bad size: %s", s);
    v = strtoul(s, &e, 10);
    if (errno) fatal("bad size: %s", s);
    if (*e == 'k' || *e == 'K') { mul = 1024UL; e++; }
    else if (*e == 'm' || *e == 'M') { mul = 1024UL * 1024UL; e++; }
    else if (*e == 'g' || *e == 'G') { mul = 1024UL * 1024UL * 1024UL; e++; }
    if (*e || v > ULONG_MAX / mul) fatal("bad size: %s", s);
    return v * mul;
}

/* every byte promised to stdout was delivered, or the status says not */
static int finish(int status)
{
    if (fflush(stdout) != 0 || ferror(stdout)) {
        warnx_("stdout: write failed");
        if (status == EX_OK) status = EX_USAGE;
    }
    return status;
}

/* the manual, through $PAGER (default more) when stdout is a terminal */
static int print_manual(void)
{
    FILE *o = stdout;
    if (isatty(STDOUT_FILENO)) {
        const char *pg = getenv("PAGER");
        if (!pg || !*pg) pg = "more";
        signal(SIGPIPE, SIG_IGN);               /* the reader may quit early */
        o = popen(pg, "w");
        if (!o) o = stdout;
    }
    for (size_t k = 0; k < MANUAL_PARTS; k++) fputs(manual_parts[k], o);
    if (o != stdout) { pclose(o); return EX_OK; }
    return finish(EX_OK);
}

static const struct { const char *name; int key, arg; } longopts[] = {
    {"in-place", 'i', 0}, {"output", 'o', 1}, {"config", 'c', 1},
    {"report", 'r', 0}, {"dry-run", 'n', 0}, {"list", 'l', 0},
    {"keep", 'k', 0}, {"marker", 'm', 1}, {"strict", 's', 0},
    {"max-size", 'M', 1}, {"allow-binary", 'B', 0}, {"verbose", 'v', 0},
    {"block", 'b', 1},
    {"quiet", 'q', 0}, {"usage", 'h', 0},
    {"no-defaults", 1, 0}, {"help", 2, 0}, {"manual", 2, 0}, {"version", 3, 0},
};

/* apply one option; informational options answer and exit here */
static void set_opt(int key, const char *val)
{
    switch (key) {
    case 'i': opt_inplace = 1; break;
    case 'n': opt_dryrun = 1; break;
    case 'r': opt_report = 1; break;
    case 'l': opt_list = 1; break;
    case 'k': opt_keep = 1; break;
    case 's': opt_strict = 1; break;
    case 'B': opt_allow_binary = 1; break;
    case 'v': opt_verbose = 1; break;
    case 'q': opt_quiet = 1; break;
    case 'c': opt_config = val; break;
    case 'o': opt_output = val; break;
    case 'm': marker = val; marker_len = strlen(val); break;
    case 'M': opt_max_size = parse_size(val); break;
    case 'b':
        opt_block = parse_size(val);
        if (opt_block < MIN_BLOCK || opt_block > (1UL << 30))
            fatal("bad block size: %s (%u bytes to 1G)", val, MIN_BLOCK);
        break;
    case 1:   opt_no_defaults = 1; break;
    case 'h': fputs(usage_text, stdout); exit(finish(EX_OK));
    case 2:   exit(print_manual());
    case 3:   printf("%s %s rev %s\n", PROG, VERSION, REV); exit(finish(EX_OK));
    }
}

int main(int argc, char **argv)
{
    int i;

    /* options: clusters (-qs), -oFILE or -o FILE, --name, --name=VALUE */
    for (i = 1; i < argc; i++) {
        const char *a = argv[i];
        if (!strcmp(a, "--")) { i++; break; }
        if (a[0] != '-' || a[1] == '\0') break;

        if (a[1] == '-') {
            const char *eq = strchr(a, '=');
            size_t nl = eq ? (size_t)(eq - a) - 2 : strlen(a) - 2, k;
            size_t nopt = sizeof longopts / sizeof longopts[0];
            for (k = 0; k < nopt; k++)
                if (strlen(longopts[k].name) == nl &&
                    !memcmp(longopts[k].name, a + 2, nl)) break;
            if (k == nopt) fatal("unknown option: %s (try -h)", a);
            if (!longopts[k].arg) {
                if (eq) fatal("--%s takes no value", longopts[k].name);
                set_opt(longopts[k].key, NULL);
            } else if (eq) set_opt(longopts[k].key, eq + 1);
            else {
                if (++i >= argc) fatal("%s requires a value", a);
                set_opt(longopts[k].key, argv[i]);
            }
            continue;
        }

        for (const char *c = a + 1; *c; c++) {
            if (!strchr("inrlksBvqhcomMb", *c))
                fatal("unknown option: -%c (try -h)", *c);
            if (strchr("comMb", *c)) {
                const char *val = c[1] ? c + 1 : NULL;
                if (!val) {
                    if (++i >= argc) fatal("-%c requires a value", *c);
                    val = argv[i];
                }
                set_opt(*c, val);
                break;
            }
            set_opt(*c, NULL);
        }
    }

    if (opt_inplace && opt_output) fatal("-i and -o are mutually exclusive");
    if (opt_output && argc - i > 1) fatal("-o takes exactly one input file");

    Table t;
    table_init(&t, TRANSLIT_TABLE_N + 256);
    if (!opt_no_defaults) table_load_defaults(&t);
    config_discover(&t, opt_config);
    if (t.multi_n > 1) qsort(t.multi, t.multi_n, sizeof *t.multi, multi_cmp);

    if (opt_list) { table_list(&t); table_free(&t); return finish(EX_OK); }

    int from_stdin = i >= argc;
    if (from_stdin) {
        if (isatty(STDIN_FILENO))
            fatal("no input: name a file, or pipe text to standard input "
                  "(try -h)");
        if (opt_inplace) fatal("-i needs a named file");
        if (opt_output) fatal("-o needs a named file; redirect standard "
                              "output instead");
    }

    if ((opt_inplace || opt_output) && !opt_dryrun && !opt_report) {
        struct sigaction sa, old;
        int sigs[] = { SIGINT, SIGTERM, SIGHUP };
        memset(&sa, 0, sizeof sa);
        sa.sa_handler = on_signal;
        sigemptyset(&sa.sa_mask);
        for (size_t k = 0; k < sizeof sigs / sizeof sigs[0]; k++)
            if (sigaction(sigs[k], NULL, &old) == 0 && old.sa_handler != SIG_IGN)
                sigaction(sigs[k], &sa, NULL);
    }

    int status = EX_OK;
    Stats total = {0, 0, 0, 0, 0};

    if (from_stdin) {
        if (filter_stdin(&t, &total) != 0) status = EX_USAGE;
        if (opt_verbose)
            warnx_("stdin: %zu -> %zu bytes, %zu replaced, %zu unmapped, "
                   "%zu invalid", total.bytes_in, total.bytes_out,
                   total.replaced, total.unmapped, total.invalid);
    }

    for (; i < argc; i++) {
        const char *name = argv[i], *path = name;
        char *rp = NULL;
        unsigned char *in = NULL;
        size_t len = 0;
        mode_t mode = 0644;

        /* in place through a symlink rewrites the file, not the link */
        if (opt_inplace) {
            rp = realpath(name, NULL);
            if (!rp) {
                warnx_("%s: cannot process (%s)", name, strerror(errno));
                if (status == EX_OK) status = EX_USAGE;
                continue;
            }
            path = rp;
        }

        if (slurp(path, name, &in, &len, &mode) != 0) {
            if (status == EX_OK) status = EX_USAGE;
            free(rp);
            continue;
        }

        Buf out;
        buf_init(&out, len + len / 8 + 64);
        Stats st = {0, 0, 0, 0, 0};
        Conv cs = {0, 0, '\n'};
        convert(&t, in, len, 1, &out, &st, &cs);
        st.bytes_in = len;
        st.bytes_out = out.n;

        /* an in-place file that needs nothing keeps inode, links and mtime */
        int same = out.n == len && memcmp(out.p, in, len) == 0;
        free(in);

        if (!opt_dryrun && !opt_report) {
            int rc = 0;
            if (opt_inplace) { if (!same) rc = write_atomic(path, out.p, out.n, mode); }
            else if (opt_output) rc = write_out(opt_output, out.p, out.n);
            else rc = write_stdout(out.p, out.n);
            if (rc != 0) status = EX_USAGE;
        }
        free(out.p);
        free(rp);

        total.bytes_in += st.bytes_in;
        total.bytes_out += st.bytes_out;
        total.replaced += st.replaced;
        total.unmapped += st.unmapped;
        total.invalid += st.invalid;

        if (opt_verbose)
            warnx_("%s: %zu -> %zu bytes, %zu replaced, %zu unmapped, "
                   "%zu invalid%s", name, st.bytes_in, st.bytes_out,
                   st.replaced, st.unmapped, st.invalid,
                   opt_inplace && same ? ", unchanged" : "");
    }

    if (opt_report) census_print();

    if (!opt_quiet && !opt_verbose && !opt_report &&
        (total.unmapped || total.invalid))
        warnx_("%zu unmapped, %zu invalid (--report lists them)",
               total.unmapped, total.invalid);

    if (opt_strict && (total.unmapped || total.invalid) && status == EX_OK)
        status = EX_UNMAPPED;

    table_free(&t);
    return finish(status);
}
